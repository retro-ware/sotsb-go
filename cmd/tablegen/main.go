// Command tablegen writes engine/tables.go: the data tables of the DOS
// START.EXE that the engine reads, as named Go values. It runs only at
// `go generate` time (engine/tables_spec.go), so the game itself never reads
// the executable.
//
// Tables marked Curse are still read from Curse of the Azure Bonds'
// START.EXE until the code using them is re-ported.
//
//	tablegen BLADES-START.EXE CURSE-START.EXE > tables.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"

	"sotsb/exe"
	"sotsb/tablespec"
)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: tablegen BLADES-START.EXE CURSE-START.EXE")
	}
	blades, err := exe.LoadBlades(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	curse, err := exe.LoadCurse(os.Args[2])
	if err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/tablegen from START.EXE; DO NOT EDIT.\n\npackage engine\n\n")
	for _, t := range tablespec.Tables {
		if t.Doc != "" {
			for _, l := range strings.Split(t.Doc, "\n") {
				fmt.Fprintf(&b, "// %s\n", l)
			}
		}
		n := t.Len
		if t.Cols > 0 {
			n *= t.Cols
		}
		img := blades
		if t.Curse {
			img = curse
		}
		rowSize := t.Cols * t.Kind.Size()
		if t.Stride > 0 {
			rowSize = t.Stride
		}
		raw := img.Bytes(t.At, n*t.Kind.Size())
		if t.Cols > 0 {
			raw = img.Bytes(t.At, t.Len*rowSize)
			typ := map[tablespec.Kind]string{tablespec.Bytes: "byte", tablespec.Signed: "int8", tablespec.Words: "uint16", tablespec.SignedWords: "int16", tablespec.Longs: "int32"}[t.Kind]
			fmt.Fprintf(&b, "var %s = [%d][%d]%s{\n", t.Name, t.Len, t.Cols, typ)
			for r := 0; r < t.Len; r++ {
				row := raw[r*rowSize : r*rowSize+t.Cols*t.Kind.Size()]
				fmt.Fprintf(&b, "{%s},\n", list(row, t.Kind.Size(), t.Kind == tablespec.Signed || t.Kind == tablespec.SignedWords || t.Kind == tablespec.Longs))
			}
			b.WriteString("}\n\n")
			continue
		}
		switch t.Kind {
		case tablespec.Bytes:
			fmt.Fprintf(&b, "var %s = [%d]byte{%s}\n\n", t.Name, t.Len, list(raw, 1, false))
		case tablespec.Signed:
			fmt.Fprintf(&b, "var %s = [%d]int8{%s}\n\n", t.Name, t.Len, list(raw, 1, true))
		case tablespec.Words:
			fmt.Fprintf(&b, "var %s = [%d]uint16{%s}\n\n", t.Name, t.Len, list(raw, 2, false))
		case tablespec.SignedWords:
			fmt.Fprintf(&b, "var %s = [%d]int16{%s}\n\n", t.Name, t.Len, list(raw, 2, true))
		case tablespec.Longs:
			fmt.Fprintf(&b, "var %s = [%d]int32{%s}\n\n", t.Name, t.Len, list(raw, 4, true))
		default: // strings: Len Pascal strings of Kind.Size() bytes each
			fmt.Fprintf(&b, "var %s = [%d]string{", t.Name, t.Len)
			for i := 0; i < t.Len; i++ {
				s := raw[i*t.Kind.Size():]
				if int(s[0]) >= t.Kind.Size() { // not a string (an unused slot holding other data)
					b.WriteString(`"", `)
					continue
				}
				fmt.Fprintf(&b, "%q, ", string(s[1:1+int(s[0])]))
			}
			b.WriteString("}\n\n")
		}
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		os.Stdout.Write(b.Bytes())
		log.Fatal(err)
	}
	os.Stdout.Write(src)
}

func list(raw []byte, size int, signed bool) string {
	var parts []string
	for i := 0; i+size <= len(raw); i += size {
		v := 0
		for k := size - 1; k >= 0; k-- {
			v = v<<8 | int(raw[i+k])
		}
		if signed && v >= 1<<(8*size-1) {
			v -= 1 << (8 * size)
		}
		parts = append(parts, fmt.Sprint(v))
	}
	return strings.Join(parts, ", ")
}
